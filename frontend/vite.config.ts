import tailwindcss from "@tailwindcss/vite";
import { devtools } from "@tanstack/devtools-vite";
import { tanstackRouter } from "@tanstack/router-plugin/vite";
import { loadEnv } from "vite";
import { defineConfig, type ViteUserConfig } from "vitest/config";

// The devtools' package marketplace installs packages and edits source files from the panel;
// dependencies here are added by hand, at exact versions. 0.8.5 has no option to turn it off.
const marketplace = "@tanstack/devtools:event-client-setup";

// The stylesheet as text, for its contrast test (vitest processes no CSS otherwise).
const rawCss = /\.css\?raw$/u;

// Vitest: jsdom, the shared setup, and the coverage gate over the hand-written code.
const tests: ViteUserConfig["test"] = {
  environment: "jsdom",
  setupFiles: ["src/test/setup.ts"],
  // A file's first test loads its page's code: on a busy machine (parallel runs) that alone can
  // take seconds. Waits inside tests stay shorter (`asyncUtilTimeout` in the setup).
  testTimeout: 15_000,
  css: { include: [rawCss] },
  restoreMocks: true,
  unstubGlobals: true,
  coverage: {
    provider: "v8",
    include: ["src/**"],
    exclude: [
      "src/**/*.test.{ts,tsx}",
      "src/test/**",
      "src/**/*.d.ts",
      "src/client/**", // generated
      "src/routeTree.gen.ts", // generated
      "src/components/ui/**", // generated by `shadcn add`
      "src/hooks/use-mobile.ts", // generated by `shadcn add`
    ],
    thresholds: { lines: 85, functions: 85, branches: 85, statements: 85 },
  },
};

// `make dev` runs this dev server (5173) next to FastAPI (the profile's WEB__PORT) and proxies
// `/api` to it, so the browser sees one origin. Builds go to `dist/`, which FastAPI serves.
export default defineConfig(({ mode }) => {
  const { WEB__PORT: apiPort = "8000" } = loadEnv(mode, ".", "WEB__");
  return {
    plugins: [
      // First, as its sub-plugins must run before the others. It strips the devtools
      // (`routes/__root.tsx`) from every build, the shell included, which does not strip itself.
      devtools({
        removeDevtoolsOnBuild: true,
        injectSource: { enabled: true }, // "go to source" from the page
        consolePiping: { enabled: false }, // its endpoint answers any origin (ACAO: *)
        enhancedLogs: { enabled: false },
      }).filter((plugin) => plugin.name !== marketplace),
      // File-based routes (src/routes) -> src/routeTree.gen.ts (committed); each page is its own chunk.
      tanstackRouter({
        target: "react",
        autoCodeSplitting: true,
        routeFileIgnorePattern: String.raw`\.test\.tsx?$`,
        quoteStyle: "double",
        semicolons: true,
      }),
      tailwindcss(),
    ],
    server: {
      port: 5173,
      strictPort: true,
      // One origin from the browser's view: the session cookie and the CSRF check
      // (`Sec-Fetch-Site: same-origin`) work as they are, and the sign-in redirects are relative.
      proxy: { "/api": `http://127.0.0.1:${apiPort}` },
    },
    build: {
      license: true, // third-party licenses -> dist/.vite/license.md
      modulePreload: { polyfill: false }, // no inline script: the CSP allows none
      rolldownOptions: {
        // "use client" matters for server rendering only; this app renders in the browser alone.
        onwarn(warning, warn) {
          if (warning.code !== "MODULE_LEVEL_DIRECTIVE") {
            warn(warning);
          }
        },
      },
    },
    test: tests,
  };
});
