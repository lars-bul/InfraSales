def _script(*operations: ops.MigrateOperation, message: str | None = None) -> ops.MigrationScript:
    return ops.MigrationScript(
        rev_id=None,
        message=message,
        upgrade_ops=ops.UpgradeOps(ops=list(operations)),
        downgrade_ops=ops.DowngradeOps(ops=[]),
    )


def _process(script: ops.MigrationScript, *, autogenerate: bool) -> list[ops.MigrationScript]:
    config = Config()
    config.set_main_option("script_location", "infrasales:migrations")
    config.cmd_opts = argparse.Namespace(autogenerate=autogenerate)
    directives = [script]
    schema.revision_directives(config)(MagicMock(), "head", directives)
    return directives


def _table() -> Table:
    return Table("source", MetaData(), Column("id", Integer, primary_key=True))


def test_autogenerated_revisions_are_numbered_and_named_after_their_changes() -> None:
    script = _script(ops.CreateTableOp.from_table(_table()))

    _process(script, autogenerate=True)

    head, _ = schema.revisions()
    assert script.rev_id == f"{int(head or 0) + 1:04d}"
    assert script.message == "add table source"


def test_an_explicit_message_is_kept() -> None:
    script = _script(ops.CreateTableOp.from_table(_table()), message="add news sources")

    _process(script, autogenerate=True)

    assert script.message == "add news sources"


def test_empty_autogenerated_revisions_are_not_written() -> None:
    assert _process(_script(), autogenerate=True) == []


def test_hand_written_revisions_are_numbered_too() -> None:
    script = _script(message="backfill")

    assert _process(script, autogenerate=False) == [script]
    assert script.rev_id is not None
    assert script.rev_id.isdigit()


def test_descriptions_skip_index_changes_unless_alone() -> None:
    table = Table("job_run", MetaData(), Column("id", Integer), Column("trigger", String))
    added_column = ("add_column", None, "job_run", table.c.trigger)
    added_index = ("add_index", table.indexes)
    existing = {"existing_nullable": True}
    modified = [("modify_type", None, "job_run", "id", existing, Integer(), String())]

    assert schema.describe([("add_table", table), added_index]) == "add table job_run"
    assert schema.describe([added_column, modified]) == (
        "add column job_run trigger modify type job_run id"
    )
    assert schema.describe([("remove_index", None)]) == "remove index"


def _previous_revision() -> str | None:
    """The revision before this build's head: None while the history has only one."""
    script = schema.check_history(schema.alembic_config(""))
    head_id = script.get_current_head()
    head = script.get_revision(head_id) if head_id else None
    previous = head.down_revision if head else None
    return previous if isinstance(previous, str) else None


PREVIOUS = _previous_revision()
AHEAD = "UPDATE alembic_version SET version_num = '9999'"  # migrated by a newer build
DROP_ACTIVE = "DROP INDEX uq_job_run_active_manual"
NARROWER = (  # one queued manual run per job, but any number running
    "CREATE UNIQUE INDEX uq_job_run_active_manual ON job_run (job)"
    " WHERE trigger = 'manual' AND status = 'pending'"
)


async def _suits_build(url: str, *changes: str) -> bool:
    db = Database(url)
    async with db.engine.begin() as connection:
        for change in changes:
            await connection.exec_driver_sql(change)
    suits = await schema.suits_build(db)
    await db.dispose()
    return suits


@pytest.mark.anyio
@pytest.mark.parametrize(
    ("changes", "ready"),
    [
        ((), True),  # at this build's head
        (("DELETE FROM alembic_version",), False),  # never migrated
        pytest.param(  # at an older revision this build knows: `migrate` has not run
            (f"UPDATE alembic_version SET version_num = '{PREVIOUS}'",),  # noqa: S608  # our own revision ID
            False,
            marks=pytest.mark.skipif(
                PREVIOUS is None, reason="a single migration: no older revision to be at"
            ),
        ),
        ((AHEAD, "ALTER TABLE config_entry ADD COLUMN note VARCHAR(20)"), True),  # expanded
        ((AHEAD, "DROP TABLE config_entry"), False),  # contracted: a table this build reads
    ],
)
async def test_a_database_suits_the_build_at_its_head_or_ahead_if_still_usable(
    tmp_path: Path, changes: tuple[str, ...], *, ready: bool
) -> None:
    url = f"sqlite+aiosqlite:///{tmp_path}/schema.db"
    schema.upgrade(url)

    assert await _suits_build(url, *changes) is ready


@pytest.mark.parametrize(
    ("changes", "usable"),
    [
        (["ALTER TABLE config_entry ADD COLUMN note VARCHAR(20)"], True),
        (["ALTER TABLE config_entry ADD COLUMN kind VARCHAR(20) NOT NULL DEFAULT 'x'"], True),
        (["DROP TABLE config_entry"], False),
        (["ALTER TABLE config_entry DROP COLUMN revision"], False),  # a column this build uses
        (["DROP INDEX uq_job_run_active_manual"], False),  # "Run now" relies on it to conflict
        ([DROP_ACTIVE, "CREATE INDEX uq_job_run_active_manual ON job_run (job)"], False),  # same
        ([DROP_ACTIVE, NARROWER], False),  # the same name, no longer what the build relies on
        (["CREATE UNIQUE INDEX ix_extra ON config_entry (key, revision)"], True),  # one more
        (["DROP INDEX ix_audit_event_created_at"], False),  # retention's index
        pytest.param(  # SQLite cannot drop a constraint without rebuilding the table
            ["ALTER TABLE config_entry DROP CONSTRAINT uq_config_entry_key"],
            False,
            marks=postgres_only,
        ),
        pytest.param(  # the same name, other columns: a run's steps would no longer conflict
            [
                "ALTER TABLE job_step DROP CONSTRAINT uq_job_step_run_id_name",
                "ALTER TABLE job_step ADD CONSTRAINT uq_job_step_run_id_name UNIQUE (run_id)",
            ],
            False,
            marks=postgres_only,
        ),
        pytest.param(  # this build leaves it empty for scheduled runs
            ["ALTER TABLE job_run ALTER COLUMN triggered_by SET NOT NULL"],
            False,
            marks=postgres_only,
        ),
        pytest.param(  # a default does not help: finishing a run writes NULL there
            [
                "ALTER TABLE job_run ALTER COLUMN lease_owner SET DEFAULT 'x'",
                "ALTER TABLE job_run ALTER COLUMN lease_owner SET NOT NULL",
            ],
            False,
            marks=postgres_only,
        ),
        pytest.param(  # inserts by this build would leave it empty: SQLite cannot even add it
            [
                "ALTER TABLE config_entry ADD COLUMN owner VARCHAR(20) NOT NULL DEFAULT 'x'",
                "ALTER TABLE config_entry ALTER COLUMN owner DROP DEFAULT",
            ],
            False,
            marks=postgres_only,
        ),
    ],
)
def test_a_schema_is_usable_while_it_has_what_this_build_uses(
    database_url: str, changes: list[str], *, usable: bool
) -> None:
    engine = create_engine(schema.sync_url(database_url))
    with engine.connect() as connection:
        transaction = connection.begin()
        for change in changes:
            connection.exec_driver_sql(change)
        result = schema.usable(connection)
        transaction.rollback()  # DDL is transactional on both databases
    engine.dispose()

    assert result is usable


@pytest.mark.anyio
async def test_readiness_refuses_a_schema_the_build_would_fail_on(database_url: str) -> None:
    """The index keeps its name, its predicate changes: "Run now" would fail on it."""
    db = Database(database_url)
    async with db.engine.begin() as connection:
        for change in (DROP_ACTIVE, NARROWER):
            await connection.exec_driver_sql(change)

    async with db.engine.connect() as connection:
        ready = await connection.run_sync(schema.usable)
    with pytest.raises(DBAPIError):  # no index matches its ON CONFLICT any more
        async with db.session() as session:
            await runs.enqueue(session, "scrape", utcnow(), triggered_by="basic:alice")
    await db.dispose()

    assert ready is False


def test_two_migrations_with_one_number_are_refused(tmp_path: Path) -> None:
    """Two branches both generated the next number: refused, never one silently skipped."""
    copy = tmp_path / "migrations"
    shutil.copytree(MIGRATIONS, copy, ignore=shutil.ignore_patterns("__pycache__"))
    newest = max((copy / "versions").glob("*.py"))
    shutil.copy(newest, newest.with_name(f"{newest.stem}_on_another_branch.py"))
    config = Config()
    config.set_main_option("script_location", str(copy))

    with pytest.raises(RuntimeError, match="present more than once: two branches"):
        schema.check_history(config)
    assert schema.check_history(schema.alembic_config("")).get_current_head() == newest.name[:4]


